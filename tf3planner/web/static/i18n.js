// Translate a Russian source string and fill {0}, {1}, ...
function loc(text, ...args) {
  const s = (LANG === "en" && I18N_EN[text]) || text;
  return args.length ? s.replace(/\{(\d+)\}/g, (m, i) => (args[i] === undefined ? m : args[i])) : s;
}

// fetch() that tells the server which language to answer in
function apiFetch(url, opts = {}) {
  return fetch(url, { ...opts, headers: { ...(opts.headers || {}), "X-Lang": LANG } });
}

function localizeDom(root = document.body) {
  document.documentElement.lang = LANG;
  if (document.title in I18N_EN) document.title = loc(document.title);
  if (LANG !== "en") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const raw = n.nodeValue.replace(/\s+/g, " ").trim();
    if (raw && raw in I18N_EN) n.nodeValue = n.nodeValue.replace(n.nodeValue.trim(), I18N_EN[raw]);
  }
  root.querySelectorAll("[title], [placeholder]").forEach((el) => {
    for (const a of ["title", "placeholder"]) {
      const v = el.getAttribute(a);
      if (v && v in I18N_EN) el.setAttribute(a, I18N_EN[v]);
    }
  });
}

// RU / EN switch: <div class="lang-switch"><button data-lang="ru">RU</button><button data-lang="en">EN</button></div>
function initLangSwitch() {
  document.querySelectorAll(".lang-switch button").forEach((b) => {
    b.classList.toggle("on", b.dataset.lang === LANG);
    b.onclick = () => {
      if (b.dataset.lang === LANG) return;
      try { localStorage.setItem(LANG_KEY, b.dataset.lang); } catch (e) { /* not saved */ }
      // the plan for the in-game blueprint follows the same language
      fetch("/api/control/settings", { method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ lang: b.dataset.lang }) }).catch(() => {}).finally(() => location.reload());
    };
  });
}

localizeDom();
initLangSwitch();
