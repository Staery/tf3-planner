// Interface language of the TF3 Planner web pages (map and control center): Russian / English.
// The pages are written in Russian; I18N_EN maps every Russian string to English. Strings with
// values use numbered placeholders: loc("Год {0}", y). Static HTML text is translated by
// localizeDom(). API answers come back already translated (the X-Lang header, see apiFetch).
// Switching the language reloads the page: everything the pages show comes from the server.
// The block between the I18N_EN markers is plain JSON (tests/test_i18n.py reads it).

const LANG_KEY = "tf3.lang";

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "ru" || saved === "en") return saved;
  } catch (e) { /* storage blocked */ }
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "";
  return /^(ru|be|uk|kk)/i.test(nav) ? "ru" : "en";
}

